def main():
    with open(ZH_FILE, "r", encoding="utf-8") as f:
        zh_data = json.load(f)

    en_data = []
    missing_count = 0
    for item in zh_data:
        str_id = item["id"]
        zh_text = item["zh"]
        if str_id in TRANSLATIONS:
            en_text = TRANSLATIONS[str_id]
        elif not zh_text.strip():
            en_text = ""
        else:
            print(f"Warning: Missing translation for ID {str_id}: {zh_text}")
            en_text = zh_text
            missing_count += 1

        en_data.append({
            "id": str_id,
            "hex_id": item["hex_id"],
            "zh": zh_text,
            "en": en_text,
        })

    with open(EN_FILE, "w", encoding="utf-8") as f:
        json.dump(en_data, f, ensure_ascii=False, indent=2)

    print(f"Exported {len(en_data)} short strings to {EN_FILE}")
    print(f"Total translated: {len(TRANSLATIONS)}, Missing: {missing_count}")

if __name__ == "__main__":
    main()
